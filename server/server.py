def decode_audio_bytes(data: bytes) -> np.ndarray:
    """Decode any common audio format to float32 mono @ SR using PyAV."""
    import av

    resampler = av.AudioResampler(format="s16", layout="mono", rate=SR)
    frames = []
    samples = 0
    with av.open(io.BytesIO(data)) as container:
        for frame in container.decode(audio=0):
            for out in resampler.resample(frame):
                frames.append(out.to_ndarray().ravel())
                samples += out.samples
            if samples >= SR * 30:
                break
    for out in resampler.resample(None):
        frames.append(out.to_ndarray().ravel())
    if not frames:
        raise ValueError("No audio found in file")
    return np.concatenate(frames)[:SR * 30].astype(np.float32) / 32768.0


class M4aWriter:
    """Progressive AAC/m4a encoder (PyAV)."""

    def __init__(self, path: Path):
        import av

        self.av = av
        self.container = av.open(str(path), "w")
        self.stream = self.container.add_stream("aac", rate=SR)
        self.stream.bit_rate = 64_000
        self.stream.layout = "mono"

    def write(self, pcm16: bytes):
        if not pcm16:
            return
        n = len(pcm16) // 2
        frame = self.av.AudioFrame(format="s16", layout="mono", samples=n)
        frame.sample_rate = SR
        frame.planes[0].update(pcm16)
        for pkt in self.stream.encode(frame):
            self.container.mux(pkt)

    def close(self):
        try:
            for pkt in self.stream.encode(None):
                self.container.mux(pkt)
        finally:
            self.container.close()


class JobCancelled(Exception):
    pass


def to_pcm16(tensor) -> bytes:
    a = tensor.detach().cpu().numpy().ravel()
    a = np.clip(a * 32767.0, -32768, 32767).astype("<i2")
    return a.tobytes()


