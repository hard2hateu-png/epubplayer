@app.post("/api/tts")
async def tts(body: dict):
    ok, res = await _engine_submit("prepare_tts", body)
    if ok != "ok":
        raise HTTPException(422, res)
    job_id = res["job_id"]
    meta = {
        "job_id": job_id,
        "_vs": res["_vs"],
        "_segs": res["_segs"],
        "_job_dir": res["_job_dir"],
        "chars": res["chars"],
        "voice_label": body.get("voice_label", "voice"),
        "title": body.get("title", "narration"),
    }
    # fire the (long-running) generation on the engine thread
    engine.q.put(("tts", meta, queue.Queue()))

    job_dir = OUT_DIR / job_id
    frames = job_dir / "frames.bin"
    done_f = job_dir / "DONE"
    cancel_f = job_dir / "CANCEL"
    fail_f = job_dir / "FAIL"

    async def stream():
        import asyncio

        off = 0
        while True:
            try:
                size = frames.stat().st_size
            except FileNotFoundError:
                size = 0
            if off < size:
                with open(frames, "rb") as f:
                    f.seek(off)
                    data = f.read(min(1 << 20, size - off))
                off += len(data)
                yield data
                continue
            if done_f.exists() or cancel_f.exists() or fail_f.exists():
                break
            await asyncio.sleep(0.15)

    return StreamingResponse(
        stream(),
        media_type="application/octet-stream",
        headers={
            "X-Job-Id": job_id,
            "X-Sample-Rate": str(SR),
            "X-Segments": str(res["segments"]),
            "X-Est-Seconds": str(res["est_seconds"]),
            "Cache-Control": "no-store",
        },
    )


