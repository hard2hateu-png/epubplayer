@app.middleware("http")
async def protect_app(request: Request, call_next):
    if request.url.path != "/health" and ACCESS_KEY:
        supplied = request.headers.get("x-pocket-key", "")
        if not secrets.compare_digest(supplied, ACCESS_KEY):
            return JSONResponse({"detail": "Open Pocket TTS using your private app link."}, status_code=401)
    response = await call_next(request)
    response.headers["X-Content-Type-Options"] = "nosniff"
    if request.url.path.startswith("/api/"):
        response.headers["Cache-Control"] = "no-store"
    return response


