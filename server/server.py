def split_text(text: str, max_chars: int = 400):
    """Split text into (segment, ends_paragraph) chunks for steady generation."""
    text = re.sub(r"[ \t]+", " ", text)
    paras = re.split(r"\n\s*\n", text)
    units = []  # (sentence, last_of_paragraph)
    for p in paras:
        p = re.sub(r"\n", " ", p).strip()
        if not p:
            continue
        ss = [s.strip() for s in re.split(r"(?<=[.!?])\s+(?=[A-Z0-9\"']|\()", p)]
        ss = [s for s in ss if s]
        if not ss:
            ss = [p[i : i + max_chars] for i in range(0, len(p), max_chars)]
        for k, s in enumerate(ss):
            units.append((s, k == len(ss) - 1))

    segs = []
    buf, buf_flag = "", False
    for s, is_last in units:
        if buf and len(buf) + len(s) + 1 > max_chars:
            segs.append((buf, buf_flag))
            buf, buf_flag = s, is_last
        else:
            buf = (buf + " " + s) if buf else s
            buf_flag = is_last
        while len(buf) > max_chars + 150:
            cut = buf.rfind(" ", 0, max_chars)
            if cut < 80:
                cut = max_chars
            segs.append((buf[:cut].strip(), False))
            buf, buf_flag = buf[cut + 1 :], False
    if buf.strip():
        segs.append((buf.strip(), buf_flag))
    return segs


def clean_for_tts(text: str) -> str:
    text = re.sub(r"https?://\S+|www\.\S+", " web link ", text)
    return text.strip()


