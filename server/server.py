@app.get("/api/download/{job_id}")
def download(job_id: str):
    if not re.fullmatch(r"[a-f0-9]{12}", job_id):
        raise HTTPException(404, "Job not found")
    p = OUT_DIR / job_id / "audio.m4a"
    if not p.exists() or not (p.parent / "DONE").exists():
        raise HTTPException(404, "Not found (the file may have been pruned).")
    meta = next((j for j in _jobs() if j["id"] == job_id), None)
    title = re.sub(r"[^A-Za-z0-9 _\-]", "", (meta or {}).get("title", "narration")).strip() or "narration"
    return FileResponse(p, media_type="audio/mp4", filename=f"{title[:60]}.m4a")


