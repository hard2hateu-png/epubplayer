@app.get("/api/jobs/{job_id}")
def job_status(job_id: str):
    if not re.fullmatch(r"[a-f0-9]{12}", job_id):
        raise HTTPException(404, "Job not found")
    d = OUT_DIR / job_id
    if not d.exists():
        raise HTTPException(404, "Job not found")
    if (d / "FAIL").exists():
        return {"status": "failed", "error": (d / "FAIL").read_text()}
    if (d / "CANCEL").exists():
        return {"status": "cancelled"}
    return {"status": "done" if (d / "DONE").exists() else "generating"}


