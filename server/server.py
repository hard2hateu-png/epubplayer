@app.post("/api/setup")
def setup(body: dict):
    token = (body.get("token") or "").strip()
    if not token:
        raise HTTPException(400, "Missing token")
    try:
        r = httpx.get(
            "https://huggingface.co/api/whoami",
            headers={"Authorization": f"Bearer {token}"},
            timeout=20,
        )
    except Exception as e:  # noqa: BLE001
        raise HTTPException(502, f"Could not reach HuggingFace: {e}")
    if r.status_code != 200:
        raise HTTPException(401, "That token was rejected by HuggingFace.")
    user = r.json().get("name", "user")
    ok, res = engine.submit("setup", {"token": token})
    if ok != "ok":
        raise HTTPException(500, f"Setup failed: {res}")
    return {"ok": True, "hf_user": user, **res}


