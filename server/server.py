class Engine:
    def __init__(self):
        self.q: "queue.Queue" = queue.Queue()
        self.model = None
        self.cloning_enabled = False
        self.load_lock = threading.Lock()
        self.load_error = None
        self.loading = False
        threading.Thread(target=self._loop, daemon=True, name="engine").start()

    # -- model ----------------------------------------------------------
    def _ensure_model(self):
        with self.load_lock:
            if self.model is not None:
                return self.model
            t0 = time.time()
            if LOCAL_CONFIG.exists():
                self.model = TTSModel.load_model(config=str(LOCAL_CONFIG))
            else:
                self.model = TTSModel.load_model(language="english")
            self.cloning_enabled = bool(getattr(self.model, "has_voice_cloning", False))
            self.load_error = None
            print(f"[engine] model ready in {time.time()-t0:.1f}s cloning={self.cloning_enabled}", flush=True)
        return self.model

    def warm_up(self):
        try:
            self._ensure_model()
        except Exception as e:  # noqa: BLE001
            print(f"[engine] warm-up failed: {e}", flush=True)
            self.load_error = str(e)
        finally:
            self.loading = False

    # -- job loop ---------------------------------------------------------
    def _loop(self):
        while True:
            job = self.q.get()
            kind, payload, out = job
            try:
                getattr(self, f"_do_{kind}")(payload, out)
            except (ValueError, HTTPException) as e:  # expected client errors
                print(f"[engine] {kind} rejected: {e}", flush=True)
                out.put(("error", str(e)))
            except Exception as e:  # noqa: BLE001
                import traceback

                traceback.print_exc()
                out.put(("error", str(e)))

    def submit(self, kind, payload):
        """Blocking submit used by sync-context endpoints (engine is threaded)."""
        out: "queue.Queue" = queue.Queue()
        self.q.put((kind, payload, out))
        try:
            return out.get(timeout=600)
        except queue.Empty:
            return ("error", "The speech engine is busy. Please try again shortly.")

    # -- voice state ------------------------------------------------------
    def _voice_state(self, payload):
        model = self._ensure_model()
        if payload.get("voice_builtin"):
            name = payload["voice_builtin"]
            if name not in BUILTIN_IDS:
                raise ValueError(f"Unknown built-in voice '{name}'")
            p = MODELS_DIR / "wc" / "languages" / "english" / "embeddings" / f"{name}.safetensors"
            if not p.exists():
                from huggingface_hub import hf_hub_download

                p = Path(
                    hf_hub_download(
                        repo_id="kyutai/pocket-tts-without-voice-cloning",
                        filename=f"languages/english/embeddings/{name}.safetensors",
                        revision=REV_EMB,
                    )
                )
            return model.get_state_for_audio_prompt(str(p))
        b64 = payload.get("voice_state_b64")
        if not b64:
            raise ValueError("No voice supplied")
        tmp = OUT_DIR / f"_state_{uuid.uuid4().hex}.safetensors"
        if not isinstance(b64, str) or len(b64) > 32_000_000:
            raise ValueError("Voice file is too large.")
        tmp.write_bytes(base64.b64decode(b64, validate=True))
        try:
            return model.get_state_for_audio_prompt(str(tmp))
        finally:
            tmp.unlink(missing_ok=True)

    # -- clone ------------------------------------------------------------
    def _do_clone(self, payload, out):
        model = self._ensure_model()
        if not self.cloning_enabled:
            raise ValueError(
                "Voice cloning needs the full model. Open Setup and connect your HuggingFace token."
            )
        arr = decode_audio_bytes(payload["file_bytes"])
        dur = len(arr) / SR
        if dur < 3.0:
            raise ValueError(f"Sample is {dur:.1f}s — record at least 3 seconds (5–30s is ideal).")
        if dur > 30.0:
            arr = arr[: int(30.0 * SR)]
            dur = 30.0
        t0 = time.time()
        state = model.get_state_for_audio_prompt(torch.from_numpy(arr).unsqueeze(0))
        tmp = OUT_DIR / f"_vstate_{uuid.uuid4().hex}.safetensors"
        export_model_state(state, tmp)
        size = tmp.stat().st_size
        out.put(("ok", {
            "state_b64": base64.b64encode(tmp.read_bytes()).decode("ascii"),
            "duration_s": round(dur, 1),
            "size_mb": round(size / 1e6, 1),
            "encode_s": round(time.time() - t0, 1),
        }))
        tmp.unlink(missing_ok=True)

    # -- preview -----------------------------------------------------------
    def _do_preview(self, payload, out):
        model = self._ensure_model()
        vs = self._voice_state(payload)
        text = payload.get("text") or PREVIEW_TEXT
        audio = model.generate_audio(vs, text)
        pcm = to_pcm16(audio)
        wav = _wav_bytes(pcm, SR)
        out.put(("ok", {"wav": wav, "duration_s": round(len(pcm) / 2 / SR, 1)}))

    # -- tts prepare + stream ----------------------------------------------
    def _do_prepare_tts(self, payload, out):
        model = self._ensure_model()
        text = clean_for_tts(payload.get("text", ""))
        if len(text) < 2:
            raise ValueError("Nothing to read — enter some text or upload a file first.")
        if len(text) > 500_000:
            raise ValueError("Please generate one chapter or section at a time (up to 500,000 characters).")
        vs = self._voice_state(payload)  # validates the voice early
        segs = split_text(text)
        job_id = uuid.uuid4().hex[:12]
        job_dir = OUT_DIR / job_id
        job_dir.mkdir(parents=True, exist_ok=True)
        est_s = len(text) / 15.0
        out.put(("ok", {
            "job_id": job_id,
            "segments": len(segs),
            "chars": len(text),
            "est_seconds": int(est_s),
            "_vs": vs,
            "_segs": segs,
            "_job_dir": job_dir,
        }))

    def _do_tts(self, payload, out):
        model = self._ensure_model()
        vs = payload["_vs"]
        segs = payload["_segs"]
        job_dir: Path = payload["_job_dir"]
        job_id = payload["job_id"]
        title = (payload.get("title") or "narration")[:80]
        cancel_f = job_dir / "CANCEL"

        frames_path = job_dir / "frames.bin"
        m4a_path = job_dir / "audio.m4a"
        writer = M4aWriter(m4a_path)
        pcm_total = 0
        t0 = time.time()
        cancelled = False
        failure = None
        try:
            with open(frames_path, "wb", buffering=0) as f:
                for i, (seg, para_end) in enumerate(segs):
                    if cancel_f.exists():
                        raise JobCancelled()
                    for chunk in model.generate_audio_stream(vs, seg, copy_state=True):
                        if cancel_f.exists():
                            raise JobCancelled()
                        pcm = to_pcm16(chunk)
                        f.write(struct.pack("<I", len(pcm)) + pcm)
                        writer.write(pcm)
                        pcm_total += len(pcm)
                    gap = 0.5 if para_end else 0.25
                    gap_pcm = b"\x00\x00" * int(SR * gap)
                    f.write(struct.pack("<I", len(gap_pcm)) + gap_pcm)
                    writer.write(gap_pcm)
                    pcm_total += len(gap_pcm)
                    if i % 5 == 4:
                        print(f"[tts {job_id}] seg {i+1}/{len(segs)} {time.time()-t0:.0f}s", flush=True)
        except JobCancelled:
            print(f"[tts {job_id}] cancelled after {time.time()-t0:.0f}s", flush=True)
            cancelled = True
        except Exception as e:  # noqa: BLE001
            print(f"[tts {job_id}] failed: {e}", flush=True)
            failure = str(e)
        finally:
            writer.close()
        if cancelled:
            frames_path.unlink(missing_ok=True)
            m4a_path.unlink(missing_ok=True)
            out.put(("done", {"cancelled": True}))
            return
        if failure:
            (job_dir / "FAIL").write_text(failure)
            out.put(("error", failure))
            return
        (job_dir / "DONE").touch()
        meta = {
            "id": job_id,
            "title": title,
            "voice": payload.get("voice_label", "voice"),
            "created": int(time.time()),
            "duration_s": round(pcm_total / 2 / SR, 1),
            "chars": payload.get("chars", 0),
        }
        _save_job(meta)
        out.put(("done", meta))

    # -- setup (gated model) ------------------------------------------------
    def _do_setup(self, payload, out):
        token = payload["token"]
        from huggingface_hub import hf_hub_download

        t0 = time.time()
        files = {
            "ptt/languages/english/model.safetensors": (
                "kyutai/pocket-tts", "languages/english/model.safetensors", REV_MODEL, True),
            "wc/languages/english/tokenizer.model": (
                "kyutai/pocket-tts-without-voice-cloning", "languages/english/tokenizer.model", REV_TOK, False),
        }
        for name in BUILTIN_IDS:
            files[f"wc/languages/english/embeddings/{name}.safetensors"] = (
                "kyutai/pocket-tts-without-voice-cloning",
                f"languages/english/embeddings/{name}.safetensors", REV_EMB, False,
            )
        for rel, (repo, fname, rev, gated) in files.items():
            dest = MODELS_DIR / rel
            if dest.exists() and dest.stat().st_size > 0:
                continue
            dest.parent.mkdir(parents=True, exist_ok=True)
            hf_hub_download(
                repo_id=repo,
                filename=fname,
                revision=rev,
                token=token if gated else None,
                local_dir=str(MODELS_DIR / rel.split("/")[0]),
            )
        # local config: package english.yaml with local paths
        from pocket_tts.utils.config import CONFIGS_DIR

        src = (CONFIGS_DIR / "english.yaml").read_text()
        src = re.sub(
            r"^weights_path:.*$",
            f"weights_path: {MODELS_DIR}/ptt/languages/english/model.safetensors",
            src,
            flags=re.M,
        )
        src = re.sub(
            r"^(\s*)tokenizer_path:.*$",
            rf"\1tokenizer_path: {MODELS_DIR}/wc/languages/english/tokenizer.model",
            src,
            flags=re.M,
        )
        LOCAL_CONFIG.write_text(src)

        # reload model with the local (voice-cloning) weights
        with self.load_lock:
            if self.model is not None:
                del self.model
                self.model = None
            gc.collect()
            self.model = TTSModel.load_model(config=str(LOCAL_CONFIG))
            self.cloning_enabled = bool(getattr(self.model, "has_voice_cloning", False))
            if not self.cloning_enabled:
                raise ValueError("The full voice-cloning model could not be loaded.")
            self.load_error = None
            READY_FLAG.write_text(f"ok {time.time()}\n")
        print(f"[setup] done in {time.time()-t0:.0f}s cloning={self.cloning_enabled}", flush=True)
        out.put(("ok", {"cloning_enabled": self.cloning_enabled, "seconds": round(time.time() - t0)}))


def _wav_bytes(pcm16: bytes, sr: int) -> bytes:
    h = io.BytesIO()
    h.write(b"RIFF")
    h.write(struct.pack("<I", 36 + len(pcm16)))
    h.write(b"WAVEfmt ")
    h.write(struct.pack("<IHHIIHH", 16, 1, 1, sr, sr * 2, 2, 16))
    h.write(b"data")
    h.write(struct.pack("<I", len(pcm16)))
    h.write(pcm16)
    return h.getvalue()


def _jobs():
    if JOBS_FILE.exists():
        try:
            return json.loads(JOBS_FILE.read_text())
        except Exception:  # noqa: BLE001
            return []
    return []


def _save_job(meta):
    jobs = _jobs()
    jobs = [j for j in jobs if j["id"] != meta["id"]]
    jobs.insert(0, meta)
    old_jobs = jobs[6:]
    jobs = jobs[:6]
    JOBS_FILE.write_text(json.dumps(jobs, indent=1))
    # prune finished-but-old job dirs only (never touch in-flight jobs)
    keep = {j["id"] for j in jobs[:6]}
    for j in old_jobs:
        d = OUT_DIR / j["id"]
        if d.is_dir():
            import shutil

            shutil.rmtree(d, ignore_errors=True)


